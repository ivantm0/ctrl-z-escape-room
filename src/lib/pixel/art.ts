const cache = new Map<string, HTMLCanvasElement>();

/** Convierte un patrón (dígitos hexadecimales = índice de la paleta) en un lienzo de 8 × 8 */
export function bake(pattern: Pattern, palette: string[] = PALETTE) {
  const key = pattern.join('|') + palette.join();
  let c = cache.get(key);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = TILE;
  c.height = TILE;
  const g = c.getContext('2d')!;
  pattern.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === '.') return;
      g.fillStyle = palette[parseInt(ch, 16)];
      g.fillRect(x, y, 1, 1);
    })
  );
  cache.set(key, c);
  return c;
}

export const tile = (name: keyof typeof P) => bake(P[name]);
export const sprite = (name: keyof typeof S) => bake(S[name]);

/** Loseta base (suelo) sobre la que se dibujan los objetos transparentes */
export function floorFor(screen: string) {
  return screen === 'casa' ? 'planks' : screen === 'cueva' ? 'caveFloor' : 'grass';
}
